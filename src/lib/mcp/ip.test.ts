import { describe, expect, it } from "vitest";

import { allowEntryFor, cidrContains, isLoopback, normalizeCidr } from "./ip";

describe("normalizeCidr", () => {
  it.each([
    ["203.0.113.5", "203.0.113.5/32"],
    ["203.0.113.0/24", "203.0.113.0/24"],
    ["2001:db8::1", "2001:db8::1/128"],
    [" \t203.0.113.129/25\n", "203.0.113.128/25"],
    ["10.255.255.255/8", "10.0.0.0/8"],
    ["2001:0DB8:0000:0000:0000:0000:0000:0001/32", "2001:db8::/32"],
    ["2001:db8:1:2:3:4:5:6/64", "2001:db8:1:2::/64"],
    ["2001:0:0:1:0:0:1:1", "2001::1:0:0:1:1/128"],
    ["2001:db8:0:1:2:3:4:5", "2001:db8:0:1:2:3:4:5/128"],
    ["::", "::/128"],
    ["::ffff:203.0.113.5", "203.0.113.5/32"],
    ["::FFFF:cb00:7105/120", "203.0.113.0/24"],
    ["::ffff:10.0.0.1/104", "10.0.0.0/8"],
    ["::192.0.2.1", "::c000:201/128"],
  ])("%s を %s に正規化する", (input, expected) => {
    expect(normalizeCidr(input)).toBe(expected);
    expect(normalizeCidr(expected)).toBe(expected);
  });

  it.each([
    "0.0.0.0/0", "::/0", "10.0.0.0/7", "abc", "", "   ",
    "203.0.113.5/33", "2001:db8::/31", "2001:db8::/129",
    "203.0.113.5/-1", "203.0.113.5/+24", "203.0.113.5/24.0",
    "203.0.113.5/24junk", "203.0.113.5/", "203.0.113.5/24/32",
    "203.0.113.5 /24", "203.0.113.5/ 24", "203.0.113.5:80",
    "203.0.113.256", "203.00.113.5", "127.1", "[::1]", "fe80::1%eth0",
    "2001:::1", "::ffff:203.0.113.5/103", "::ffff:203.0.113.5/129",
  ])("不正または広すぎる範囲 %s を拒否する", (input) => {
    expect(normalizeCidr(input)).toBeNull();
  });
});

describe("cidrContains", () => {
  it.each([
    ["203.0.113.0/24", "203.0.113.0", true],
    ["203.0.113.0/24", "203.0.113.255", true],
    ["203.0.113.0/24", "203.0.114.0", false],
    ["203.0.113.128/25", "203.0.113.127", false],
    ["203.0.113.128/25", "203.0.113.128", true],
    ["203.0.113.5/32", "203.0.113.6", false],
    ["203.0.113.0/24", "::ffff:203.0.113.5", true],
    ["203.0.113.0/24", "0:0:0:0:0:ffff:cb00:7105", true],
    ["::ffff:203.0.113.0/120", "203.0.113.5", true],
    ["203.0.113.0/24", "::ffff:203.0.114.5", false],
    ["203.0.113.0/24", "2001:db8::1", false],
    ["2001:db8::/32", "203.0.113.5", false],
    ["2001:db8::/32", "2001:db8:ffff:ffff:ffff:ffff:ffff:ffff", true],
    ["2001:db8::/32", "2001:db9::", false],
    ["2001:db8::/65", "2001:db8::7fff:ffff:ffff:ffff", true],
    ["2001:db8::/65", "2001:db8::8000:0:0:0", false],
    ["2001:db8::1/128", "2001:db8::1", true],
    ["2001:db8::1/128", "2001:db8::2", false],
    ["abc", "203.0.113.5", false],
    ["203.0.113.0/24", "abc", false],
    ["203.0.113.0/24", "203.0.113.5/32", false],
    ["0.0.0.0/0", "203.0.113.5", false],
    ["::/0", "2001:db8::1", false],
    ["fe80::/64", "fe80::1%eth0", false],
  ])("%s に %s が含まれるか判定する", (cidr, ip, expected) => {
    expect(cidrContains(cidr, ip)).toBe(expected);
  });
});

describe("isLoopback", () => {
  it.each([
    ["127.0.0.1", true], ["127.0.0.0", true], ["127.255.255.255", true],
    ["::1", true], ["0:0:0:0:0:0:0:1", true],
    ["::ffff:127.0.0.1", true], ["::ffff:7fff:ffff", true],
    ["192.168.0.1", false], ["128.0.0.1", false], ["::", false],
    ["::127.0.0.1", false], ["::ffff:192.168.0.1", false],
    ["abc", false], ["127.0.0.1/8", false], ["::1%lo", false],
  ])("%s のループバック判定", (ip, expected) => {
    expect(isLoopback(ip)).toBe(expected);
  });
});

describe("allowEntryFor", () => {
  it.each([
    ["203.0.113.5", "203.0.113.5/32"],
    ["2001:db8:1:2:3:4:5:6", "2001:db8:1:2::/64"],
    ["2001:DB8::1234", "2001:db8::/64"],
    ["::1", "::/64"],
    ["::ffff:203.0.113.5", "203.0.113.5/32"],
    ["::ffff:cb00:7105", "203.0.113.5/32"],
    ["abc", null], ["203.0.113.5/24", null], ["fe80::1%eth0", null],
  ])("%s の登録範囲を返す", (ip, expected) => {
    expect(allowEntryFor(ip)).toBe(expected);
  });
});
